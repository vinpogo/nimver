func isAutoGenerated*(raw: string): bool =
  raw.startsWith("fixup! ") or raw.startsWith("squash! ") or raw.startsWith("amend! ")

proc cmdCheckCommitMsg*(
    repoRoot: string, msgFilePath: string, effects: var Effects
): Result[int, string] =
  ## The exit code. A refused message is said as it is, and fails the commit
  ## with 1; failing to check it at all is an error like any other.
  let raw = ?readFileContents(msgFilePath)
  if isAutoGenerated(raw):
    return ok(0)
  let parsed = parseCommitMessage(raw).valueOr:
    effects.add(warn(error))
    return ok(1)
  let config = ?loadUserConfig(repoRoot)
  if config.validateAndLookup(parsed).isNone:
    effects.add(warn("nimver: unknown commit type '" & parsed.commitType & "'"))
    return ok(1)
  ok(0)
